// Indian grouping: crore, lakh, thousand (2 digits each), then hundreds.
const UNITS = [
  [10000000, 'करोड़'],
  [100000, 'लाख'],
  [1000, 'हज़ार'],
  [100, 'सौ'],
];

export function hindiNumber(n) {
  if (!Number.isInteger(n) || n < 0 || n > 99999999) throw new RangeError(`Cannot say ${n} in Hindi`);
  if (n < 100) return BELOW_100[n];
  const words = [];
  let rest = n;
  for (const [size, name] of UNITS) {
    const count = Math.floor(rest / size);
    if (count > 0) {
      words.push(hindiNumber(count), name);
      rest -= count * size;
    }
  }
  if (rest > 0) words.push(BELOW_100[rest]);
  return words.join(' ');
}
